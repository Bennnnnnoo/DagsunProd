"""Cut sprites out of sprite_sheet.jpg for the site.

usage: python3 scripts/cut-sprites.py sprite_sheet.jpg src/assets/sprites

Each sprite is cropped, its dark grey background keyed out, and a 1px dark
outline added so its white/grey parts still read on the light theme. Writes one
PNG per sprite plus index.ts. Skips the large 0-4 digits (the sheet's watermark
runs across them) and the weapon/ammo icons.
Needs ImageMagick (magick).
"""
import os, subprocess, sys

src, out_dir = sys.argv[1], sys.argv[2]

BACKGROUND = "srgb(50,50,50)"
FUZZ = "13%"  # how far from the background colour still counts as background (JPEG noise)

# name: (x, y, w, h) in the 640x480 sheet
SPRITES = {
    "digit5": (298, 0, 52, 56),
    "digit6": (360, 0, 54, 56),
    "digit7": (426, 0, 52, 56),
    "digit8": (480, 0, 54, 56),
    "digit9": (543, 0, 56, 56),
    "small1": (434, 147, 24, 42),
    "small2": (479, 147, 34, 42),
    "small3": (529, 147, 34, 42),
    "small4": (429, 186, 38, 44),
    "small5": (481, 186, 36, 44),
    "shield": (4, 55, 52, 47),
    "shieldOutline": (64, 55, 52, 47),
    "shieldDome": (4, 249, 54, 50),
    "shieldDome2": (62, 249, 54, 50),
    "plus": (120, 54, 50, 48),
    "plusSmall": (555, 56, 41, 32),
    "minus": (524, 61, 32, 22),
    "dollar": (484, 54, 34, 50),
    "stopwatch": (364, 144, 52, 48),
    "circleR": (161, 297, 78, 60),
    "circleE": (322, 297, 78, 60),
    "circleV": (402, 297, 78, 60),
    "cart": (244, 297, 74, 52),
    "figure": (21, 359, 38, 64),
    "figureSmall": (91, 359, 26, 32),
    "figureMedium": (1, 424, 32, 56),
}

# Sprites with stray red from the watermark's glow, removed after cropping.
DROP_RED = {"shield", "shieldOutline"}

os.makedirs(out_dir, exist_ok=True)
for name, (x, y, w, h) in SPRITES.items():
    out = os.path.join(out_dir, f"{name}.png")
    subprocess.run([
        "magick", src, "-crop", f"{w}x{h}+{x}+{y}", "+repage",
        # Key out the background, then drop JPEG speckle (tiny isolated bits).
        "-fuzz", FUZZ, "-transparent", BACKGROUND,
        *(["-fuzz", "18%", "-transparent", "srgb(200,40,40)"] if name in DROP_RED else []),
        "-channel", "A", "-morphology", "Open", "Square:1", "+channel",
        # 1px dark outline underneath, grown from the sprite's shape.
        "(", "+clone", "-alpha", "extract", "-morphology", "Dilate", "Square:1",
        "-background", "#141414", "-alpha", "shape", ")",
        "+swap", "-background", "none", "-compose", "Over", "-flatten",
        "-trim", "+repage", "-strip", out,
    ], check=True)

names = list(SPRITES)
ts = ["// Generated by scripts/cut-sprites.py. Do not edit by hand.", ""]
ts += [f'import {n} from "./{n}.png";' for n in names]
ts += ["", "export const sprites = {", *[f"  {n}," for n in names], "};", "", "export type SpriteName = keyof typeof sprites;", ""]
open(os.path.join(out_dir, "index.ts"), "w").write("\n".join(ts))
print(f"wrote {len(names)} sprites to {out_dir}")
